"""
Create and validate the receipt picking for a non-warranty without-serial ticket.
Args: <ticket_id> <picking_id>
  ticket_id:  the helpdesk ticket id
  picking_id: the reference outgoing picking created by action_create_repair_serial

This replicates the stock.return.picking wizard flow that the "Receipt" button opens.
For the without-serial path, the lot comes from the ticket's x_studio_serial_no
(which was set by action_create_repair_serial).

Returns JSON with receiptPickingId, receiptPickingName, receiptState,
ticketValidReturn, ticketValidConfirmReturn.
"""
import os, sys, json
os.environ['ODOO_RC'] = '/etc/odoo/odoo.conf'
import odoo
from odoo.tools import config
config.parse_config(['-c', '/etc/odoo/odoo.conf'])

ticket_id = int(sys.argv[1])
source_picking_id = int(sys.argv[2])

with odoo.registry('odoo17').cursor() as cr:
    env = odoo.api.Environment(cr, odoo.SUPERUSER_ID, {})
    ticket = env['helpdesk.ticket'].browse(ticket_id)
    source_pick = env['stock.picking'].browse(source_picking_id)
    company = env['res.company'].browse(1)

    if not ticket.exists():
        print(json.dumps({'error': f'Ticket {ticket_id} not found'}))
        sys.exit(1)

    # Validate that action_create_repair_serial has run (serial must be set)
    if not ticket.x_studio_serial_no:
        print(json.dumps({'error': 'ticket.x_studio_serial_no not set — run action_create_repair_serial first'}))
        sys.exit(1)

    if not ticket.x_studio_virtual_location or not ticket.x_studio_source_location:
        print(json.dumps({'error': 'Virtual/source locations not set on ticket'}))
        sys.exit(1)

    # Find source location (where item is coming from = customer)
    source_loc = env['stock.location'].search([('usage', '=', 'customer')], limit=1)

    # Find incoming (Returns) picking type destined for the return_receipt_location
    opt_type = env['stock.picking.type'].search([
        ('default_location_dest_id', '=', ticket.x_studio_return_receipt_location.id),
        ('code', '=', 'incoming'),
        ('company_id', '=', company.id),
    ], limit=1)

    if not opt_type:
        # Fallback: any incoming picking type for this company
        opt_type = env['stock.picking.type'].search([
            ('code', '=', 'incoming'),
            ('company_id', '=', company.id),
        ], limit=1)

    if not opt_type:
        print(json.dumps({'error': 'No incoming picking type found'}))
        sys.exit(1)

    print(f'  Using picking type: id={opt_type.id} "{opt_type.name}" dest={opt_type.default_location_dest_id.complete_name}', file=sys.stderr)

    # Create receipt picking (mirrors SA1009 / stock.return.picking flow)
    receipt = env['stock.picking'].create({
        'x_studio_helpdesk_ticket_id': ticket.id,
        'picking_type_id': opt_type.id,
        'location_id': source_loc.id,
        'location_dest_id': opt_type.default_location_dest_id.id,
        'origin': 'Return of ' + source_pick.name,
        'partner_id': ticket.partner_id.id,
        'company_id': company.id,
    })

    move = env['stock.move'].create({
        'picking_id': receipt.id,
        'name': 'New Move:' + ticket.product_id.name,
        'reference': receipt.name,
        'picking_type_id': receipt.picking_type_id.id,
        'product_id': ticket.product_id.id,
        'location_id': receipt.location_id.id,
        'location_dest_id': receipt.location_dest_id.id,
        'product_uom_qty': 1.0,
        'product_uom': ticket.product_id.uom_id.id,
        'state': 'assigned',
        'company_id': company.id,
    })

    ml = env['stock.move.line'].create({
        'move_id': move.id,
        'picking_id': receipt.id,
        'picking_type_id': receipt.picking_type_id.id,
        'product_id': ticket.product_id.id,
        'product_uom_id': ticket.product_id.uom_id.id,
        'location_id': receipt.location_id.id,
        'location_dest_id': receipt.location_dest_id.id,
        'lot_id': ticket.x_studio_serial_no.id,  # serial was generated by action_create_repair_serial
        'quantity': 1.0,
        'picked': True,
        'company_id': company.id,
    })

    # Link receipt to ticket
    ticket.write({'picking_ids': [(4, receipt.id)]})

    # Validate the receipt picking
    receipt._action_done()
    cr.commit()

    # Refresh and check
    ticket.invalidate_recordset()
    print(json.dumps({
        'receiptPickingId': receipt.id,
        'receiptPickingName': receipt.name,
        'receiptState': receipt.state,
        'ticketValidReturn': ticket.x_studio_valid_return,
        'ticketValidConfirmReturn': ticket.x_studio_valid_confirm_return,
        'serialName': ticket.x_studio_serial_no.name if ticket.x_studio_serial_no else None,
    }))
